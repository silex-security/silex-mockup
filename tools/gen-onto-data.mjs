/** JSON as written to disk. */
export const serialize = x => JSON.stringify(x, null, 2) + '\n';

/** Contract D, with the vendored commit read from jev-runtime/VENDORED.json. */
export function buildSlice(root = ROOT) {
  const vendored = JSON.parse(readFileSync(join(root, 'jev-runtime/VENDORED.json'), 'utf8'));
  return sliceExport({ vendoredCommit: vendored.commit });
}

/** Every *.json under root matching MATCH (node_modules and dot-directories skipped), as sorted '/'-separated paths. */
export function walkMatches(root = ROOT) {
  const out = [];
  const walk = dir => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.name.startsWith('.') || e.name === 'node_modules') continue;
      const full = join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.isFile() && e.name.endsWith('.json')) {
        const rel = relative(root, full).split(sep).join('/');
        if (MATCH.test(rel)) out.push(rel);
      }
    }
  };
  walk(root);
  return out.sort();
}

const folderOf = path => {
  const d = path.slice(EXP.length).split('/').slice(0, -1).join('/');
  return d || '.';
};

/**
 * Contract E. `sliceBytes` is the size of the slice file about to be written (so a first run, or an in-memory
 * regeneration, does not depend on what is on disk); every other size comes from the file system.
 */
export function buildFilesList(root = ROOT, { sliceBytes } = {}) {
  const paths = [...new Set([...walkMatches(root), ...ALSO])];
  const order = new Map(GROUPS.map((g, i) => [g.id, i]));
  const rows = paths.map(path => {
    let text;
    if (path.startsWith(EXP)) {
      const folder = folderOf(path);
      text = FOLDER_TEXT[folder] && { group: 'experiments', ...FOLDER_TEXT[folder] };
      if (!text) throw new Error(`no description for experiment folder "${folder}" (${path})`);
    } else {
      text = FILE_TEXT[path];
      if (!text) throw new Error(`no description for matched file ${path}`);
    }
    const row = { path, group: text.group };
    if (path !== FILES_PATH) {
      if (path === SLICE_PATH && sliceBytes != null) row.bytes = sliceBytes;
      else if (existsSync(join(root, path))) row.bytes = statSync(join(root, path)).size;
      else throw new Error(`listed file is missing: ${path}`);
    }
    row.holds = text.holds;
    row.usedBy = text.usedBy;
    return row;
  });
  rows.sort((a, b) => order.get(a.group) - order.get(b.group) || (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const used = new Set(rows.filter(r => r.group === 'experiments').map(r => folderOf(r.path)));
  const folders = Object.fromEntries(Object.keys(FOLDER_TEXT).filter(f => used.has(f)).map(f => [f, FOLDER_TEXT[f].holds]));
  return { note: 'Generated by tools/gen-onto-data.mjs; do not edit.', rule: RULE, groups: GROUPS, folders, files: rows };
}

/** Both files as the strings that go to disk. */
export function generate(root = ROOT) {
  const slice = serialize(buildSlice(root));
  const files = serialize(buildFilesList(root, { sliceBytes: Buffer.byteLength(slice) }));
  return { [SLICE_PATH]: slice, [FILES_PATH]: files };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  for (const [path, text] of Object.entries(generate())) {
    writeFileSync(join(ROOT, path), text);
    console.log(`wrote ${path} (${Buffer.byteLength(text)} bytes)`);
  }
}
